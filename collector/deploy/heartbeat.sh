#!/usr/bin/env bash
# Heartbeat: «всё норм» по коллекторам маркетдаты и поллерам, плюс детектор тишины.
#
# Зачем отдельно от OnFailure=. OnFailure ловит юнит, который УПАЛ. Он не ловит юнит,
# который жив и ничего не делает, и не ловит таймер, который перестал отстреливать.
# Измерено 2026-08-12: params-poller.timer молча не срабатывал 23 часа
# (`Trigger: n/a` после рестарта), юнит числился enabled, ни одного алерта не пришло,
# и поймал это человек случайным вопросом. Это тот класс отказа, который виден только
# по ОТСУТСТВИЮ свежих записей.
#
# Почему heartbeat, а не только тревоги. Если сообщения приходят только на проблему,
# тишина двусмысленна: либо всё хорошо, либо сломался сам сторож. Периодическое
# «всё норм» делает тишину однозначной — её отсутствие и есть тревога.
# Ровно та же логика, по которой поллеры пишут ПУЛЬС, а не только изменения.
#
# Дёшево по построению: смотрим ТОЛЬКО mtime новейшего файла (`find -newermt … -quit`,
# выход на первом попадании). Никакой распаковки. Хост сбора не должен нести нагрузку.
#
# Запускается СИСТЕМНЫМ юнитом от root — иначе не прочитать alert.env (root:600).
# Каталоги поллеров живут в домашнем каталоге сервисного пользователя, поэтому путь
# к ним задаётся явно (POLLER_HOME), а не через $HOME: у root он другой.
#
# Запуск:  heartbeat.sh [--dry-run]
# Конфиг:  /opt/hft-collector/etc/alert.env  (тот же, что у alert.sh)
#            TG_BOT_TOKEN, TG_CHAT_ID
#            HEARTBEAT_DIGEST_EVERY_S  как часто слать «всё норм» (по умолчанию 14400 = 4 ч)
#            HEARTBEAT_STALE_OVERRIDE  пороги свежести на инстанс: «имя:минуты имя:минуты»
#            HEARTBEAT_STALE_WEEKEND_MIN  порог для них же в субботу/воскресенье (4000)
#            HEARTBEAT_STALE_RATE_S  не чаще одной тревоги в N секунд (по умолчанию 3600)

set -uo pipefail

DRY_RUN=0
[[ "${1:-}" == "--dry-run" ]] && DRY_RUN=1

ENV_FILE=/opt/hft-collector/etc/alert.env
DATA_ROOT=/opt/hft-collector/data
ETC_DIR=/opt/hft-collector/etc
STAMP=/run/hft-collector-heartbeat.stamp
POLLER_HOME="${POLLER_HOME:-/home/ubuntu}"
HOST="$(hostname -s)"

# Порог свежести в МИНУТАХ по классам целей.
COLLECTOR_STALE_MIN=10   # пишут непрерывно; 10 мин — это уже точно не «тонкий символ»

# Инстансы, живущие по БИРЖЕВЫМ ЧАСАМ, а не круглосуточно: перпы на акции и ETF
# (корейские, американские, гонконгские). Ночью и в выходные их базовый рынок
# закрыт, поток честно вырождается в редкие котировки — и общая мерка в 10 минут
# даёт ложную тревогу каждую ночь. Замерено 23.08.2026: binancefuturesum-d
# (ZHONGJI, SAMSUNGEM, HANMI, LGELECTRONICS, NAVER, KODEX200) в 20:45 UTC субботы
# отчитался «13 минут» при живом процессе — zhongjiusdt рос на 47 КБ за 90 с.
#
# 240 минут = четыре часа. Порог не «побольше на всякий случай», а вычислен:
# он обязан пережить самую длинную ШТАТНУЮ тишину, которая не выходные (выходные
# накрываются отдельно — см. ниже), то есть ночь между сессиями. Больше суток
# ставить нельзя: тогда мёртвый шард в будний день не заметят до вечера.
#
STALE_OVERRIDE="${HEARTBEAT_STALE_OVERRIDE:-binancefuturesum-d:240 binancefuturesum-f:240 binancefuturesum-day0:240}"

# Выходные — отдельный порог, и без него предыдущая ручка бесполезна: с закрытия
# пятницы до открытия понедельника тишина законно длится до 65 часов, то есть
# четырёхчасовой порог дал бы ложную тревогу все выходные напролёт. А монитор,
# который воет каждую субботу, перестают читать — и он пропускает настоящую аварию.
#
# 4000 минут = 66.7 часа: чуть больше самой длинной ШТАТНОЙ тишины. Шард, замолчавший
# ДО закрытия рынка (в четверг или утром пятницы), в этот порог не поместится и будет
# назван. Шард, замолчавший вместе с рынком, — нет, и это правильно: собирать в
# выходные всё равно нечего, а его смерть будет видна в понедельник.
#
# Применяется ТОЛЬКО к инстансам из STALE_OVERRIDE. Круглосуточные венью живут по
# общему десятиминутному порогу все семь дней — у них выходных не бывает.
STALE_WEEKEND_MIN="${HEARTBEAT_STALE_WEEKEND_MIN:-4000}"

# Порог свежести для инстанса: переопределение, иначе общий.
stale_min_for() {
    local inst="$1" spec
    local dow; dow="$(date -u +%u)"        # 6 = суббота, 7 = воскресенье
    for spec in ${STALE_OVERRIDE}; do
        if [[ "${spec%%:*}" == "${inst}" ]]; then
            if (( dow >= 6 )); then echo "${STALE_WEEKEND_MIN}"; else echo "${spec##*:}"; fi
            return
        fi
    done
    echo "${COLLECTOR_STALE_MIN}"
}
POLLER_STALE_MIN=90      # часовой таймер + RandomizedDelaySec до 4 мин + запас
# day0-поллер тикает раз в 10 мин, и пульс он трогает ТОЛЬКО на успешном тике.
# Порог = 3 пропущенных тика (3×10 = 30 мин) + 5 мин запас = 35 мин: один провал
# сети — не событие (сам поллер алертит после 6 провалов подряд, т.е. на ~60-й
# минуте), а мёртвый таймер — класс отказа params-poller, 23 часа молчания —
# виден за полчаса. Общие 90 мин здесь не годятся: волна листинга приходит без
# предупреждения, и полтора часа слепоты стоят первых минут захвата (+13.16 бп).
DAY0_STALE_MIN=35
# funding-поллер тикает раз в 5 мин; пульс пишется, только если хоть одна нога
# площадки жива. Порог = 3 пропущенных тика (15 мин) + 5 мин запас = 20 мин.
# Тишина пульса = все ноги мертвы либо мёртв сам таймер (класс params-poller);
# частичные провалы (одна площадка из четырёх) алертит сам поллер по ногам.
FUNDING_STALE_MIN=20

if [[ -r "${ENV_FILE}" ]]; then
    # shellcheck disable=SC1090
    source "${ENV_FILE}"
fi
# Положительный пульс — раз в N секунд, а не «в такой-то час».
#
# Было: раз в сутки в 9:00 UTC. Проблема не в частоте, а в том, что признаком
# служил ЧАС, а таймер стреляет в :00 и :30 — то есть в девятом часу прогонов
# два, и дубль дайджеста жил незамеченным с 12.08, пока его не поймали штампом
# с датой. Интервальный признак этот класс убирает совсем: сравнивается время
# последней ОТПРАВКИ, а не календарная метка, поэтому сколько бы раз ни
# сработал таймер, лишнего сообщения не будет по построению.
#
# Четыре часа — это шесть сообщений в сутки: достаточно, чтобы молчание канала
# само по себе стало сигналом (сутки без зелёного = что-то сломано), и не
# настолько часто, чтобы их перестали читать. Порог видимости проблемы при
# этом НЕ меняется: проверка по-прежнему идёт каждые полчаса, и тревога уходит
# сразу — здесь настраивается только каденция «всё норм».
DIGEST_EVERY_S="${HEARTBEAT_DIGEST_EVERY_S:-14400}"
RATE_S="${HEARTBEAT_STALE_RATE_S:-3600}"

# --- гвард переполнения диска (задача #56) ------------------------------------
# Рантайм-пол в самом коллекторе есть (check_disk каждый минутный тик, чистая
# остановка с записью disk_exhausted в _meta), но он срабатывает у САМОГО пола,
# когда сбор уже умирает. Здесь — предупреждение ЗАРАНЕЕ, потому что измеренная
# 2026-08-19 цепочка отказа целиком тихая: машина оператора выключена → офлоад
# не забирает → диск заполняется ~10 ГБ/сутки → у пола останавливаются все
# инстансы разом. От 47 ГБ свободного до пола — четверо суток тишины.
# 15 ГБ ≈ полтора суток запаса: хватает проспать ночь и починить утром.
DISK_WARN_GB="${HEARTBEAT_DISK_WARN_GB:-15}"
DISK_CRIT_GB="${HEARTBEAT_DISK_CRIT_GB:-8}"
DISK_RATE_S="${HEARTBEAT_DISK_RATE_S:-21600}"   # warn: не чаще раза в 6 часов
DISK_STAMP=/run/hft-collector-heartbeat-disk.stamp
# Дайджест «всё норм» — не чаще раза в СУТКИ. Прежнее условие «час == 9» без
# штампа отправляло его дважды: таймер стреляет в :00 и :30, и оба прогона
# попадают в девятый час. Штамп хранит дату последней доставки.
DIGEST_STAMP=/run/hft-collector-heartbeat-digest.stamp

# --- проверка одной цели: есть ли файл свежее порога --------------------------
# Печатает "OK <имя> <возраст_мин>" либо "STALE <имя> <возраст_мин|nofiles>".
check_dir() {
    local name="$1" dir="$2" limit_min="$3"
    if [[ ! -d "${dir}" ]]; then
        echo "STALE ${name} nodir"; return
    fi
    if find "${dir}" -maxdepth 2 -name '*.gz' -newermt "-${limit_min} minutes" -print -quit \
        2>/dev/null | grep -q .; then
        echo "OK ${name}"
    else
        # возраст новейшего файла — только для текста сообщения, полный обход
        # каталога здесь допустим лишь потому, что мы уже знаем: свежих нет
        local newest age
        newest="$(find "${dir}" -maxdepth 2 -name '*.gz' -printf '%T@\n' 2>/dev/null \
                  | sort -rn | head -1)"
        if [[ -z "${newest}" ]]; then echo "STALE ${name} nofiles"; return; fi
        age=$(( ( $(date +%s) - ${newest%.*} ) / 60 ))
        echo "STALE ${name} ${age}m"
    fi
}

results=()

# коллекторы: по одному инстансу на <etc>/<name>.env (бэкапы .bak-* пропускаем)
for env_path in "${ETC_DIR}"/*.env; do
    [[ -e "${env_path}" ]] || continue
    inst="$(basename "${env_path}" .env)"
    [[ "${inst}" == "alert" ]] && continue
    results+=("$(check_dir "${inst}" "${DATA_ROOT}/${inst}" "$(stale_min_for "${inst}")")")
done

# поллеры: формат «имя:каталог:порог». Каталоги РАЗНЫЕ, и это не небрежность:
# day0 и funding кладут в домашний каталог сервисного пользователя (пульс), а
# params с 2026-08-22 пишет на том данных — его перенесли туда, потому что в
# домашнем каталоге он лежал на КОРНЕВОМ диске, мимо вывоза и мимо гейта, и 24 МБ
# ряда параметров существовали в одном экземпляре. Свежесть проверяется там, где
# лежат данные, а не там, где лежит лог.
# day0 — поллер листингов дня-0 (тик 10 мин), порог свой (DAY0_STALE_MIN): его тишина
# стоит дороже прочих — волна приходит раз в ~2 суток без предупреждения, и
# пропущенный листинг невосполним. Отсутствующий каталог = STALE nodir, как у всех:
# «не задеплоен» не равно «здоров».
for p in "params:${DATA_ROOT}/params:${POLLER_STALE_MIN}" \
         "positions:${DATA_ROOT}/positions:${POLLER_STALE_MIN}" \
         "day0:${POLLER_HOME}/day0-data:${DAY0_STALE_MIN}" \
         "funding:${POLLER_HOME}/funding-data:${FUNDING_STALE_MIN}"; do
    IFS=: read -r p_name p_dir p_limit <<<"${p}"
    results+=("$(check_dir "${p_name}" "${p_dir}" "${p_limit}")")
done

stale=(); ok=()
for r in "${results[@]}"; do
    read -r verdict name detail <<<"${r}"
    if [[ "${verdict}" == "OK" ]]; then ok+=("${name}"); else stale+=("${name}(${detail:-?})"); fi
done

send=""
# Свободное место — в ОБА сообщения, а не только в дайджест. В тревоге оно
# нужнее всего: «нет свежих записей» и «диск кончился» — разные аварии с разным
# первым действием, и оператор должен различать их не заходя на хост.
digest_free="$(df -BG --output=avail "${DATA_ROOT}" 2>/dev/null | tail -1 | tr -d '[:space:]')"

if (( ${#stale[@]} > 0 )); then
    send="🔴 ${HOST}: НЕТ СВЕЖИХ ЗАПИСЕЙ — ${stale[*]}"$'\n'"живы (${#ok[@]}): ${ok[*]}, диск: ${digest_free:-?} свободно"
    # рейт-лимит только на тревогу; дайджест «всё норм» ходит по расписанию
    if [[ -f "${STAMP}" ]]; then
        last=$(cat "${STAMP}" 2>/dev/null || echo 0)
        (( $(date +%s) - last < RATE_S )) && send=""
    fi
    [[ -n "${send}" ]] && date +%s > "${STAMP}"
else
    # Штамп хранит время последней ОТПРАВКИ в секундах эпохи. Пустой или
    # нечисловой (в том числе старая дата вида 20260822) читается как «давно» —
    # первый же прогон после обновления пошлёт дайджест и перезапишет штамп.
    last_digest="$(cat "${DIGEST_STAMP}" 2>/dev/null || echo 0)"
    [[ "${last_digest}" =~ ^[0-9]+$ ]] || last_digest=0
    if (( $(date +%s) - last_digest >= DIGEST_EVERY_S )); then
        send="🟢 ${HOST}: всё норм — ${#ok[@]} источников пишут свежее, диск: ${digest_free:-?} свободно"$'\n'"${ok[*]}"
    fi
fi

# --- доставка ------------------------------------------------------------------
# Возвращает 0 только при подтверждённой доставке. Успех обязан оставлять след в
# журнале: без него «отправил» и «не запускался» неразличимы — ровно так дубль
# дайджеста жил незамеченным с 12.08 (в час дайджеста журнал был просто пуст).
send_tg() {
    local text="$1"
    if (( DRY_RUN )); then
        echo "--- DRY RUN, отправлено было бы: ---"; echo "${text}"; return 0
    fi
    if [[ -z "${TG_BOT_TOKEN:-}" || -z "${TG_CHAT_ID:-}" ]]; then
        echo "heartbeat: TG не настроен; сообщение только в журнал:" >&2
        echo "${text}" >&2
        return 1
    fi
    local attempt
    for attempt in 1 2 3; do
        if curl -sS -m 10 -o /dev/null \
            --data-urlencode "chat_id=${TG_CHAT_ID}" \
            --data-urlencode "text=${text}" \
            "https://api.telegram.org/bot${TG_BOT_TOKEN}/sendMessage"; then
            echo "heartbeat: отправлено: $(head -1 <<<"${text}")"
            return 0
        fi
        # След неудачной попытки обязателен: ретрай после таймаута, когда первый
        # запрос на самом деле ДОШЁЛ, — единственный наш механизм дубля в TG, и
        # без этой строки он неотличим от одиночной доставки (разбор 2026-08-19).
        echo "heartbeat: попытка ${attempt} не доставлена, повтор через 5 с" >&2
        sleep 5
    done
    # Недоставленный алерт остаётся в журнале. Ненулевой код процесса запустил бы
    # OnFailure самого сторожа — петля; поэтому наружу всегда выходим нулём.
    echo "heartbeat: доставка не удалась; текст остаётся в журнале:" >&2
    echo "${text}" >&2
    return 1
}

sent_something=0
if [[ -n "${send}" ]]; then
    send_tg "${send}" && sent_something=1
    # Штамп дайджеста пишется ТОЛЬКО после подтверждённой доставки и только вне
    # dry-run: упавший Telegram не должен съесть дайджест на сутки — следующий
    # получас довезёт.
    if [[ "${send}" == 🟢* ]] && (( sent_something )) && (( ! DRY_RUN )); then
        date +%s > "${DIGEST_STAMP}"
    fi
fi

# --- гвард диска: считается ПОСЛЕ свежести, шлётся отдельным сообщением --------
free_bytes="$(df -B1 --output=avail "${DATA_ROOT}" 2>/dev/null | tail -1 | tr -d '[:space:]')"
if [[ "${free_bytes}" =~ ^[0-9]+$ ]]; then
    free_gb=$(( free_bytes / 1024 / 1024 / 1024 ))
    level=0
    (( free_gb < DISK_WARN_GB )) && level=1
    (( free_gb < DISK_CRIT_GB )) && level=2
    if (( level > 0 )); then
        last_level=0; last_epoch=0
        if [[ -f "${DISK_STAMP}" ]]; then
            read -r last_level last_epoch < "${DISK_STAMP}" 2>/dev/null || true
            [[ "${last_level}" =~ ^[0-9]+$ ]] || last_level=0
            [[ "${last_epoch}" =~ ^[0-9]+$ ]] || last_epoch=0
        fi
        rate="${DISK_RATE_S}"; (( level == 2 )) && rate="${RATE_S}"
        # Эскалация warn → crit пробивает рейт-лимит: ухудшение — новое событие.
        if (( level > last_level || $(date +%s) - last_epoch >= rate )); then
            if (( level == 2 )); then
                disk_msg="🔴 ${HOST}: ДИСК СБОРА ПОЧТИ ПОЛОН — свободно ${free_gb} ГБ (крит. порог ${DISK_CRIT_GB})."
            else
                disk_msg="🟡 ${HOST}: диск сбора заканчивается — свободно ${free_gb} ГБ (порог ${DISK_WARN_GB})."
            fi
            disk_msg+=$'\n'"У пола 5 ГБ все инстансы остановятся разом. Обычная причина: офлоад не забирает данные (машина оператора выключена или не в сети)."
            send_tg "${disk_msg}" && sent_something=1
            (( ! DRY_RUN )) && echo "${level} $(date +%s)" > "${DISK_STAMP}"
        fi
    else
        # Здоровый диск снимает штамп: следующая деградация снова тревожит сразу.
        rm -f "${DISK_STAMP}"
    fi
else
    echo "heartbeat: не смог прочитать свободное место в ${DATA_ROOT}" >&2
fi

if (( ! sent_something )); then
    echo "heartbeat: ok=${#ok[@]} stale=${#stale[@]} disk=${free_gb:-?}ГБ; сообщение не отправляется"
fi
exit 0
