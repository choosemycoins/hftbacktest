#!/usr/bin/env bash
# Сторож пульса announce-poller.
#
# ЗАЧЕМ. Сам поллер отчитывается о провале ИСТОЧНИКА, а `OnFailure=` ловит смерть
# процесса. Между этими двумя есть третье состояние, в котором никто не жалуется:
# таймер выключен или не сработал, машина спала, сеть легла целиком, токен отозван.
# Тогда прибор просто молчит — а молчание неотличимо от «на площадках ничего не
# происходит». Единственный признак — возраст пульса и то, что в нём написано.
#
# ЧТО ПРОВЕРЯЕТСЯ: (1) пульс существует; (2) он моложе потолка (по умолчанию 30 мин
# при тике раз в 5 мин — то есть шесть пропущенных тиков подряд); (3) последний тик
# доставил всё, что сформировал (`undelivered == 0`): свежий пульс при недоставке —
# это ровно та тихая слепота, ради которой поле и заведено.
#
# КАК СИГНАЛИТ: ненулевым кодом выхода. Юнит `announce-poller-pulse.service` несёт
# `OnFailure=signal-alert@%n.service`, а тот шлёт в Telegram хвост журнала — то есть
# строку, напечатанную здесь в stderr. Своих секретов у сторожа нет и не должно быть.
set -uo pipefail

PULSE="${1:-/home/storage/announce-poller/state/pulse.json}"
MAX_AGE_S="${PULSE_MAX_AGE_S:-1800}"

if [[ ! -f "${PULSE}" ]]; then
    echo "pulse_watch: ${PULSE} отсутствует — поллер не записал ни одного тика" >&2
    exit 1
fi

age=$(( $(date +%s) - $(stat -c %Y "${PULSE}") ))
if (( age >= MAX_AGE_S )); then
    echo "pulse_watch: пульсу ${age} с при потолке ${MAX_AGE_S} — announce-poller не тикает" \
         "(таймер? сеть? машина спала?). Последний пульс: $(cat "${PULSE}")" >&2
    exit 1
fi

# Читаем поле, а не грепаем строку: пульс — JSON, и его форма меняется.
undelivered=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1]))["undelivered"])' \
              "${PULSE}" 2>/dev/null)
if [[ -z "${undelivered}" ]]; then
    # Fail closed: нечитаемый пульс или пульс без поля (пре-апгрейдная версия) —
    # это «не могу сказать», а не «всё хорошо».
    echo "pulse_watch: пульс нечитаем или без поля undelivered: $(head -c 300 "${PULSE}")" >&2
    exit 1
fi
if [[ "${undelivered}" != "0" ]]; then
    echo "pulse_watch: последний тик не доставил ${undelivered} сообщений в Telegram" \
         "(токен? чат? сеть?). Пульс: $(cat "${PULSE}")" >&2
    exit 1
fi

echo "pulse_watch: ok — возраст ${age} с, недоставленных 0"
